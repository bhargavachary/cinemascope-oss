#!/usr/bin/env python3
"""Export the repository into a single text file `codebase_export.txt`.

- Text files are included verbatim, with a clear header showing their relative path.
- Binary files are NOT embedded; instead the script writes their size + SHA256.
- Skips VCS and typical virtualenv/node_modules directories.

Run from repo root: python3 scripts/export_codebase.py
"""
import os
import sys
import hashlib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
OUT = os.path.join(ROOT, 'codebase_export.txt')

EXCLUDE_DIRS = {'.git', '__pycache__', 'node_modules', '.venv', 'venv', '.idea'}
EXCLUDE_FILES = {os.path.basename(__file__), os.path.basename(OUT)}

count_files = 0
count_text = 0
count_binary = 0

def is_text_file(path, blocksize=512):
    try:
        with open(path, 'rb') as f:
            block = f.read(blocksize)
            if not block:
                return True
            # Heuristic: presence of a null byte => binary
            if b'\x00' in block:
                return False
            # Try decode
            try:
                block.decode('utf-8')
                return True
            except Exception:
                return False
    except Exception:
        return False

with open(OUT, 'w', encoding='utf-8') as out:
    out.write(f"Codebase export for: {ROOT}\n")
    out.write(f"Generated by: scripts/export_codebase.py\n")
    out.write(f"Note: binary files are referenced by size+sha256, not embedded.\n")
    out.write('\n' + ('='*80) + '\n\n')

    for dirpath, dirnames, filenames in os.walk(ROOT):
        # prune excluded directories
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS]
        for fname in sorted(filenames):
            if fname in EXCLUDE_FILES:
                continue
            full = os.path.join(dirpath, fname)
            rel = os.path.relpath(full, ROOT)
            # skip the export file itself if present
            if rel == os.path.relpath(OUT, ROOT):
                continue

            count_files += 1
            out.write('#' * 80 + '\n')
            out.write(f'FILE: {rel}\n')
            out.write('-' * 80 + '\n')

            try:
                if is_text_file(full):
                    count_text += 1
                    with open(full, 'r', encoding='utf-8', errors='replace') as fh:
                        out.write(fh.read())
                        out.write('\n\n')
                else:
                    count_binary += 1
                    size = os.path.getsize(full)
                    sha = hashlib.sha256()
                    with open(full, 'rb') as bf:
                        for chunk in iter(lambda: bf.read(8192), b''):
                            sha.update(chunk)
                    out.write(f'[BINARY FILE - not embedded] size={size} bytes sha256={sha.hexdigest()}\n\n')
            except Exception as e:
                out.write(f'[ERROR reading file: {e}]\n\n')

    out.write('\n' + ('='*80) + '\n')
    out.write('EXPORT SUMMARY\n')
    out.write(f'  total files scanned: {count_files}\n')
    out.write(f'  text files included:  {count_text}\n')
    out.write(f'  binary files noted:   {count_binary}\n')
    out.write('\nEND OF EXPORT\n')

print(f'Wrote: {OUT}')
print(f'Scanned files: {count_files} (text: {count_text}, binary: {count_binary})')
